import { test, expect } from '@playwright/test'
import { join } from 'node:path'
const projectId = '11111111-1111-1111-1111-111111111111'
test.use({ userAgent: 'Mozilla/5.0 DingTalk' })

test('single robot entries select the bound project on LAN HTTP without member setup', async ({page})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
  const groupId='33333333-3333-3333-3333-333333333333'
  await page.route('https://g.alicdn.com/dingding/dingtalk-jsapi/3.0.25/dingtalk.open.js',route=>route.fulfill({contentType:'application/javascript',body:'window.dd={chooseChat:function(){throw new Error("unexpected picker")},env:{platform:"pc"},ready:function(cb){cb()},runtime:{permission:{requestAuthCode:function(o){o.onSuccess({code:"group-code"})}}}}'}))
  await page.route('**/api/integrations/dingtalk/opl/bootstrap*',route=>route.fulfill({json:{enabled:true,corpId:'corp',companyId:'company'}}))
  await page.route('**/api/integrations/dingtalk/opl/login',route=>{
    expect(route.request().postDataJSON().groupId).toBe(groupId)
    return route.fulfill({json:{guestToken:'group-ticket',displayName:'项目提交人'}})
  })
  await page.route('**/api/integrations/dingtalk/opl/guest/projects',route=>route.fulfill({json:[{id:projectId,code:'P700014',name:'TEST 5',subprojects:[]}]}))
  await page.route('**/api/integrations/dingtalk/opl/guest/projects/*/people',route=>route.fulfill({json:[]}))
  for(const viewport of [{width:390,height:844},{width:1518,height:855}]){
    await page.setViewportSize(viewport)
    await page.goto(`http://192.168.2.8:5173/?dingtalkOpl=1&companyId=company&groupId=${groupId}`)
    await expect(page).toHaveTitle(/UPLM|PDM|PLM/)
    await expect(page.getByLabel('所属项目')).toHaveValue(projectId)
    await expect(page.getByLabel('所属项目')).toBeDisabled()
    await expect(page.getByText('已自动关联当前群绑定的项目。')).toBeVisible()
    await expect(page.getByLabel('问题描述')).toBeVisible()
    await expect(page.getByText('负责人 @ 设置',{exact:false})).toHaveCount(0)
    await expect(page.getByRole('button',{name:/确认当前群|启用负责人@/})).toHaveCount(0)
    await page.getByLabel('问题描述').fill('绑定群后直接提交的问题')
    await expect(page.getByRole('button',{name:'提交问题',exact:true})).toBeEnabled()
    await expect(page.locator('vite-error-overlay')).toHaveCount(0)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    await page.screenshot({path:join(process.env.TEMP!,`dingtalk-single-robot-${viewport.width}.png`),fullPage:true})
  }
  expect(errors).toEqual([])
})

test('DingTalk mobile submission with optional subproject and group notification', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  const view = { rootProject: { id: projectId, code: 'P700014', name: '测试项目' }, subprojects: [{ id: 'child-1', code: 'P700014-1', name: '子项目A' }], people: [{ username: 'user-1', displayName: '张三' }], rows: [] }
  await page.route('https://g.alicdn.com/dingding/dingtalk-jsapi/3.0.25/dingtalk.open.js', route => route.fulfill({ contentType: 'application/javascript', body: 'window.dd={env:{platform:"ios"},ready:function(cb){cb()},runtime:{permission:{requestAuthCode:function(o){o.onSuccess({code:"mock-code"})}}}}' }))
  await page.route('**/api/integrations/dingtalk/opl/**', route => route.fulfill({ json: route.request().method() === 'POST' ? { guestToken: 'mock-token', displayName: '张三' } : { enabled: true, corpId: 'mock-corp' } }))
  await page.route('**/api/integrations/dingtalk/opl/guest/projects', route => route.fulfill({ json: [{ ...view.rootProject, subprojects: view.subprojects }, { id: '22222222-2222-2222-2222-222222222222', code: 'P700015', name: '同群第二项目' }] }))
  await page.route(`**/api/projects/${projectId}/opl`, route => route.fulfill({ json: view }))
  await page.route('**/api/integrations/dingtalk/opl/guest/projects/*/people', route => route.fulfill({ json: [{ username: 'engineer', displayName: '现场工程师' }] }))
  let submits = 0
  await page.route(`**/api/integrations/dingtalk/opl/guest/projects/${projectId}/submit`, async route => {
    expect(route.request().headers()['x-dingtalk-session']).toBe('mock-token')
    expect(route.request().headers().authorization).toBeUndefined()
    const submitted = route.request().postDataBuffer()!.toString()
    for (const value of ['child-1','高','处理中','engineer','2026-10-20','现场已检查']) expect(submitted).toContain(value)
    submits++; await route.fulfill({ json: { number: 10, submittedBy: '张三', notificationSent: true } })
  })
  await page.goto('/?dingtalkOpl=1&groupId=33333333-3333-3333-3333-333333333333')
  await expect(page.getByText('提交人：张三')).toBeVisible()
  await expect(page.getByLabel('所属项目').locator('option')).toHaveCount(3)
  await page.getByLabel('所属项目').selectOption(projectId)
  await page.getByLabel('子项目（非必填）').selectOption('child-1')
  await page.getByLabel('问题描述').fill('现场相机支架松动')
  await page.getByLabel('优先级').selectOption('高')
  await page.getByLabel('实施状态').selectOption('处理中')
  await page.getByLabel('负责人').selectOption('engineer')
  await page.getByLabel('需求完成日期').fill('2026-10-20')
  await page.getByLabel('解决措施').fill('现场已检查')
  await page.getByLabel('图片和附件', { exact: true }).setInputFiles({ name: '现场.txt', mimeType: 'text/plain', buffer: Buffer.from('模拟现场附件') })
  await page.getByRole('button', { name: '提交问题', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('问题 #10 已提交，提交人：张三。群通知已发送。')
  expect(submits).toBe(1)
  await expect(page.getByRole('heading', { name: '问题清单' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '发送群提醒' })).toHaveCount(0)
  await expect(page.getByLabel('负责人')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
  await expect.poll(() => page.locator('.ding-opl').evaluate(element => element.scrollTop)).toBe(0)
  await page.screenshot({ path: join(process.env.TEMP!, 'dingtalk-opl-mobile.png'), fullPage: true })
})
