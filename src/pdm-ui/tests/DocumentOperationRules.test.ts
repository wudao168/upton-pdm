import { flushPromises, mount } from '@vue/test-utils'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { ElPagination, ElSwitch } from 'element-plus'
import DocumentOperationRules from '../src/components/DocumentOperationRules.vue'
import { documentOperationRules, documentRuleCategories, matchesDocumentOperationRule } from '../src/documentOperationRules'
import { documentRuleMessageCatalog } from '../src/documentRuleMessages'
import { getDocumentOperationRuleSettings, setDocumentOperationRule } from '../src/api'
vi.mock('../src/api', () => ({ getDocumentOperationRuleSettings: vi.fn(), setDocumentOperationRule: vi.fn() }))

beforeEach(() => {
  vi.mocked(getDocumentOperationRuleSettings).mockReset().mockResolvedValue({ revision: 0, disabledRuleIds: [] })
  vi.mocked(setDocumentOperationRule).mockReset()
})

describe('图档操作规则', () => {
  it('单列表默认200条，133条完整展示，23条已取消拦截且不能被旧设置重新启用', async () => {
    const wrapper = mount(DocumentOperationRules, { props: { token: 'test', canEdit: true } })
    await flushPromises()
    expect(wrapper.findAll('table')).toHaveLength(1)
    expect(wrapper.findAll('tbody tr')).toHaveLength(133)
    expect(wrapper.findComponent(ElPagination).props('pageSize')).toBe(200)
    expect(wrapper.findAllComponents(ElSwitch)).toHaveLength(110)
    expect(wrapper.findAll('tbody tr').filter(row => row.findAll('td')[1].text() === '仅提示')).toHaveLength(23)
    expect(wrapper.findAllComponents(ElSwitch).every(toggle => toggle.props('modelValue') && !toggle.props('disabled'))).toBe(true)
    expect(wrapper.findAll('th').map(th => th.text())).toEqual(['编号', '拦截', '分类', '规则', '处理方式', '报错／提示语句'])
    expect(new Set(documentOperationRules.map(rule => rule.id)).size).toBe(133)
    expect(documentOperationRules.every(rule => documentRuleCategories[rule.category])).toBe(true)
    wrapper.unmount()
  })
  it('完整旧报错仍能定位F11，并展示PLM版本优先的新处理方式', async () => {
    const wrapper = mount(DocumentOperationRules)
    await wrapper.get('input[aria-label="搜索图档规则"]').setValue('受控副本存在未核对的本地修改，已保留文件，未重定位引用：\n700022.00.SLDASM')
    expect(wrapper.findAll('tbody tr')).toHaveLength(1)
    expect(wrapper.get('tbody tr td').text()).toBe('F11')
    expect(wrapper.get('tbody').text()).toContain('本地修改、新增文件、只读、占用和旧缓存不构成拦截')
    expect(wrapper.get('tbody').text()).toContain('未重定位引用：{文件名}')
    wrapper.unmount()
  })
  it('每条规则明确登记提示原文或无独立报错说明，避免新增规则漏登记', () => {
    expect(Object.keys(documentRuleMessageCatalog).sort()).toEqual(documentOperationRules.map(rule => rule.id).sort())
    expect(documentOperationRules.every(rule => rule.messages.length > 0 || rule.messageNote.trim().length > 0)).toBe(true)
    expect(documentOperationRules.find(rule => rule.id === 'F15')?.messages[0]?.kind).toBe('日志')
    expect(documentOperationRules.find(rule => rule.id === 'B03')?.messages).toHaveLength(0)
  })
  it.each(['A-XYPC834-SUS-M5.SLDPRT', 'BP1-六角头螺栓全螺纹C级.SLDPRT'])('引用版本缺失报错定位D09：%s', async file => {
    const wrapper = mount(DocumentOperationRules)
    await wrapper.get('input[aria-label="搜索图档规则"]').setValue(`引用图档“${file}”缺少引用版本，可能为实例身份未同步或引用结构未完整读取。请刷新设计树并重新整体存档；本次父装配体未更新。实例：ROOT/PART-3；配置：默认。`)
    expect(wrapper.findAll('tbody tr')).toHaveLength(1)
    expect(wrapper.get('tbody tr td').text()).toBe('D09')
    expect(wrapper.get('tbody').text()).toContain('PLM存档基线补齐')
    wrapper.unmount()
  })
  it('提示关键字、完整动态语句和空结果均可搜索，不把普通文件名当作规则', async () => {
    const f13 = documentOperationRules.find(rule => rule.id === 'F13')!
    expect(matchesDocumentOperationRule(f13, '打开图档失败：工作副本引用校验记录未能保存：TEST.SLDPRT')).toBe(true)
    expect(matchesDocumentOperationRule(f13, '引用已定位')).toBe(true)
    expect(matchesDocumentOperationRule(documentOperationRules.find(rule => rule.id === 'H04')!, '操作失败：文件名无效。')).toBe(true)
    expect(documentOperationRules.some(rule => matchesDocumentOperationRule(rule, '700022.00.SLDASM'))).toBe(false)
    const wrapper = mount(DocumentOperationRules)
    await wrapper.get('input[aria-label="搜索图档规则"]').setValue('不存在的报错示例')
    expect(wrapper.get('tbody td').attributes('colspan')).toBe('6')
    expect(wrapper.get('tbody').text()).toBe('没有符合条件的规则')
    wrapper.unmount()
  })
  it('开关保存后重新加载保持状态，失败不会伪装为已保存', async () => {
    vi.mocked(setDocumentOperationRule).mockResolvedValueOnce({ revision: 1, disabledRuleIds: ['F11'] })
    const wrapper = mount(DocumentOperationRules, { props: { token: 'test', canEdit: true } })
    await flushPromises()
    await wrapper.get('input[aria-label="搜索图档规则"]').setValue('F11')
    wrapper.findComponent(ElSwitch).vm.$emit('change', false)
    await flushPromises()
    expect(setDocumentOperationRule).toHaveBeenCalledWith('F11', false, 0, 'test')
    expect(wrapper.findComponent(ElSwitch).props('modelValue')).toBe(false)
    wrapper.unmount()
    vi.mocked(getDocumentOperationRuleSettings).mockResolvedValue({ revision: 1, disabledRuleIds: ['F11'] })
    vi.mocked(setDocumentOperationRule).mockRejectedValueOnce(new Error('conflict'))
    const restored = mount(DocumentOperationRules, { props: { token: 'test', canEdit: true } })
    await flushPromises()
    await restored.get('input[aria-label="搜索图档规则"]').setValue('F11')
    expect(restored.findComponent(ElSwitch).props('modelValue')).toBe(false)
    restored.findComponent(ElSwitch).vm.$emit('change', true)
    await flushPromises()
    expect(restored.findComponent(ElSwitch).props('modelValue')).toBe(false)
    restored.unmount()
  })
  it('只读用户不能修改，状态读取失败明确提示而不是假定已同步', async () => {
    const viewer = mount(DocumentOperationRules, { props: { token: 'test' } })
    await flushPromises()
    expect(viewer.findAllComponents(ElSwitch).every(toggle => toggle.props('disabled'))).toBe(true)
    viewer.unmount()
    vi.mocked(getDocumentOperationRuleSettings).mockRejectedValueOnce(new Error('offline'))
    const offline = mount(DocumentOperationRules, { props: { token: 'test', canEdit: true } })
    await flushPromises()
    expect(offline.get('[role=alert]').text()).toContain('无法读取规则状态')
    expect(offline.findAllComponents(ElSwitch).every(toggle => toggle.props('disabled'))).toBe(true)
    offline.unmount()
  })
  it('搜索、分类和分页组合后显示匹配内容，筛选自动回到第一页', async () => {
    const wrapper = mount(DocumentOperationRules)
    wrapper.findComponent(ElPagination).vm.$emit('update:pageSize', 50)
    await wrapper.vm.$nextTick()
    wrapper.findComponent(ElPagination).vm.$emit('update:currentPage', 3)
    await wrapper.vm.$nextTick()
    expect(wrapper.findAll('tbody tr')).toHaveLength(33)
    await wrapper.get('nav[aria-label="图档规则分类"]').findAll('button').find(button => button.text() === '获取与打开')!.trigger('click')
    await wrapper.vm.$nextTick()
    expect(wrapper.findAll('tbody tr')).toHaveLength(27)
    expect(wrapper.findComponent(ElPagination).props('currentPage')).toBe(1)
    expect(wrapper.get('nav[aria-label="图档规则分类"] button[aria-pressed="true"]').text()).toBe('获取与打开')
    await wrapper.get('input[aria-label="搜索图档规则"]').setValue('F25')
    expect(wrapper.findAll('tbody tr')).toHaveLength(1)
    expect(wrapper.get('tbody').text()).toContain('不强制断开链接')
    wrapper.unmount()
  })
})
