import { flushPromises, mount } from '@vue/test-utils'
import ElementPlus from 'element-plus'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import BrowserCadArchiveButton from '../src/components/BrowserCadArchiveButton.vue'
import BrowserCadArchiveSettings from '../src/components/BrowserCadArchiveSettings.vue'
import type { BrowserCadTicket } from '../src/browserCadArchive'
const api = vi.hoisted(() => ({ readBrowserCadCapability: vi.fn(), readBrowserCadTicket: vi.fn(), stageBrowserCadArchive: vi.fn(), startBrowserCadArchive: vi.fn(), retryBrowserCadPreviews: vi.fn(), setBrowserCadEnabled: vi.fn() }))
vi.mock('../src/api', () => api)
vi.mock('../src/statusMessage', () => ({ ElMessage: { success: vi.fn() } }))
let wrapper: ReturnType<typeof mount> | undefined
beforeEach(() => { vi.clearAllMocks(); sessionStorage.clear(); api.readBrowserCadCapability.mockResolvedValue({ enabled: true, canArchive: true, canConfigure: true }) })
afterEach(() => { wrapper?.unmount(); wrapper = undefined; vi.useRealTimers(); document.body.innerHTML = '' })
async function open() { wrapper = mount(BrowserCadArchiveButton, { attachTo: document.body, props: { token: 'token', projectId: 'project' }, global: { plugins: [ElementPlus] } }); await flushPromises(); return wrapper }
const completed = (previewsPending?: boolean): BrowserCadTicket => ({ id: 'job', state: 'Succeeded', stage: '存档完成', files: [{ relativePath: 'ROOT.SLDASM', length: 100 }], rootPath: 'ROOT.SLDASM', archivedFiles: 2, newVersions: 1, previewsPending })
async function resume() { sessionStorage.setItem('uplm-cad-archive:project', 'job'); await open(); await wrapper!.get('.browser-cad-entry').trigger('click'); await flushPromises() }
function footerButton(label: string) { return [...document.querySelectorAll<HTMLButtonElement>('.el-dialog__footer button')].find(button => button.textContent === label)! }
function deferred<T>() { let resolve!: (value: T) => void; const promise = new Promise<T>(done => { resolve = done }); return { promise, resolve } }
async function chooseFiles(label: string, files: File[]) {
  const input = document.querySelector<HTMLInputElement>(`input[aria-label="${label}"]`)!
  Object.defineProperty(input, 'files', { value: files, configurable: true }); input.dispatchEvent(new Event('change', { bubbles: true })); await flushPromises()
}
describe('网页存档入口', () => {
  it('only shows the requested label and needs no local SolidWorks capability', async () => {
    await open(); expect(wrapper!.get('.browser-cad-entry').text()).toBe('存档')
    expect(wrapper!.get('.browser-cad-entry').attributes('disabled')).toBeUndefined()
    await wrapper!.get('.browser-cad-entry').trigger('click'); await flushPromises()
    expect(document.body.textContent).toContain('选择文件夹'); expect(document.body.textContent).toContain('选择文件')
  })
  it('hides the entry when the administrator disables it and disables unauthorized users', async () => {
    api.readBrowserCadCapability.mockResolvedValue({ enabled: false, canArchive: false, canConfigure: false })
    await open(); expect(wrapper!.find('.browser-cad-entry').exists()).toBe(false)
    api.readBrowserCadCapability.mockResolvedValue({ enabled: true, canArchive: false, reason: '当前账号没有存档权限' })
    window.dispatchEvent(new Event('pdm-browser-archive-settings')); await flushPromises()
    expect(wrapper!.get('.browser-cad-entry').attributes('disabled')).toBeDefined()
    expect(wrapper!.get('.browser-cad-entry').attributes('title')).toContain('没有存档权限')
  })
  it('receives files, confirms the root, starts a durable job and refreshes only after success', async () => {
    const ready = { id: 'job', state: 'Ready', stage: '文件已接收', files: [{ relativePath: 'ROOT.SLDASM', length: 100 }, { relativePath: 'PART.SLDPRT', length: 50 }], archivedFiles: 0, newVersions: 0 }
    api.stageBrowserCadArchive.mockResolvedValue(ready); api.startBrowserCadArchive.mockResolvedValue({ ...ready, state: 'Queued' })
    api.readBrowserCadTicket.mockResolvedValue({ ...ready, state: 'Succeeded', stage: '存档完成', archivedFiles: 2, newVersions: 1 })
    await open(); await wrapper!.get('.browser-cad-entry').trigger('click'); await flushPromises()
    const input = document.querySelector<HTMLInputElement>('input[aria-label="选择存档文件"]')!; const file = new File(['cad'], 'ROOT.SLDASM')
    Object.defineProperty(input, 'files', { value: [file] }); input.dispatchEvent(new Event('change', { bubbles: true })); await flushPromises()
    expect(api.stageBrowserCadArchive).toHaveBeenCalledWith(expect.any(String), expect.objectContaining({ projectId: 'project' }), [file], 'token')
    expect(wrapper!.emitted('archived')).toBeUndefined()
    const submit = document.querySelector<HTMLButtonElement>('.el-dialog__footer .pdm-primary-action')!
    expect(submit.textContent).toBe('存档'); submit.click(); await flushPromises()
    expect(api.startBrowserCadArchive).toHaveBeenCalledWith('job', 'ROOT.SLDASM', 'token')
    expect(wrapper!.emitted('archived')).toHaveLength(1); expect(document.body.textContent).toContain('新增 1 个版本')
  })
  it('uploads selected CAD companions together and only offers SolidWorks files as roots', async () => {
    const names = ['ROOT.SLDASM', 'PART.SLDPRT', 'source.STEP', 'other.stp', 'equation.txt', 'legacy.xls', 'design.XLSX']
    const files = names.map(name => new File(['content'], name))
    api.stageBrowserCadArchive.mockResolvedValue({ ...completed(), state: 'Ready', files: names.map(relativePath => ({ relativePath, length: 100 })) })
    await open(); await wrapper!.get('.browser-cad-entry').trigger('click'); await flushPromises()
    const accept = document.querySelector<HTMLInputElement>('input[aria-label="选择存档文件"]')!.accept.split(',')
    for (const extension of ['.sldasm', '.sldprt', '.slddrw', '.step', '.stp', '.txt', '.xls', '.xlsx', '.zip']) expect(accept).toContain(extension)
    await chooseFiles('选择存档文件', files)
    expect(api.stageBrowserCadArchive).toHaveBeenCalledWith(expect.any(String), expect.objectContaining({ projectId: 'project' }), files, 'token')
    const root = document.querySelector<HTMLSelectElement>('[aria-label="存档根图档"]')!
    expect([...root.options].map(option => option.value)).toEqual(['ROOT.SLDASM', 'PART.SLDPRT'])
    expect(root.value).toBe('ROOT.SLDASM')
    expect(footerButton('存档').disabled).toBe(false)
    expect(document.body.textContent).toContain('仅存档本套图档实际需要的文件')
  })
  it('preserves folder relative paths and reports ignored metadata without uploading it', async () => {
    const native = new File(['cad'], 'ROOT.SLDASM'), companion = new File(['step'], 'source.STEP'), metadata = new File(['{}'], 'qa-expected-drawings.json')
    Object.defineProperty(native, 'webkitRelativePath', { value: 'assembly/ROOT.SLDASM' })
    Object.defineProperty(companion, 'webkitRelativePath', { value: 'assembly/imports/source.STEP' })
    api.stageBrowserCadArchive.mockResolvedValue({ ...completed(), state: 'Ready', files: [{ relativePath: native.webkitRelativePath, length: 3 }] })
    await open(); await wrapper!.get('.browser-cad-entry').trigger('click'); await flushPromises()
    await chooseFiles('选择存档文件夹', [native, companion, metadata])
    expect(api.stageBrowserCadArchive).toHaveBeenCalledWith(expect.any(String), expect.any(Object), [native, companion], 'token')
    expect(api.stageBrowserCadArchive.mock.calls[0]![2][1].webkitRelativePath).toBe('assembly/imports/source.STEP')
    expect(document.body.textContent).toContain('已忽略 1 个不支持的文件：qa-expected-drawings.json')
    expect(document.querySelector<HTMLSelectElement>('[aria-label="存档根图档"]')!.value).toBe('assembly/ROOT.SLDASM')
  })
  it('does not upload companions alone or let them become a root', async () => {
    await open(); await wrapper!.get('.browser-cad-entry').trigger('click'); await flushPromises()
    await chooseFiles('选择存档文件', [new File(['step'], 'source.step'), new File(['table'], 'design.xlsx')])
    expect(api.stageBrowserCadArchive).not.toHaveBeenCalled()
    expect(api.startBrowserCadArchive).not.toHaveBeenCalled()
    expect(document.querySelector('.browser-cad-error')!.textContent).toContain('伴随文件不能作为根图档')
    expect(document.querySelector('[aria-label="存档根图档"]')).toBeNull()
    expect(sessionStorage.getItem('uplm-cad-archive:project')).toBeNull()
  })
  it('lets a ZIP upload obtain its valid native root from the server', async () => {
    const zip = new File(['archive'], 'assembly.ZIP')
    api.stageBrowserCadArchive.mockResolvedValue({ ...completed(), state: 'Ready', files: [{ relativePath: 'assembly/DRAWING.SLDDRW', length: 100 }] })
    await open(); await wrapper!.get('.browser-cad-entry').trigger('click'); await flushPromises()
    await chooseFiles('选择存档文件', [zip])
    expect(api.stageBrowserCadArchive).toHaveBeenCalledWith(expect.any(String), expect.any(Object), [zip], 'token')
    expect(document.querySelector<HTMLSelectElement>('[aria-label="存档根图档"]')!.value).toBe('assembly/DRAWING.SLDDRW')
    expect(document.querySelector('.browser-cad-error')).toBeNull()
    expect(footerButton('存档').disabled).toBe(false)
  })
  it('administrator setting controls both entries and is absent for ordinary users', async () => {
    api.setBrowserCadEnabled.mockResolvedValue({ enabled: false })
    wrapper = mount(BrowserCadArchiveSettings, { props: { token: 'token' } }); await flushPromises()
    expect(wrapper.text()).toContain('不影响SolidWorks插件存档')
    await wrapper.get('input[type="checkbox"]').setValue(false); await wrapper.get('button').trigger('click'); await flushPromises()
    expect(api.setBrowserCadEnabled).toHaveBeenCalledWith(false, 'token')
    wrapper.unmount(); api.readBrowserCadCapability.mockResolvedValue({ enabled: true, canArchive: true, canConfigure: false })
    wrapper = mount(BrowserCadArchiveSettings, { props: { token: 'token' } }); await flushPromises()
    expect(wrapper.find('input').exists()).toBe(false)
  })
  it('announces native success immediately, keeps archiving available and refreshes once previews finish', async () => {
    vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout'] })
    api.readBrowserCadTicket.mockResolvedValueOnce({ ...completed(), state: 'Processing', stage: '解析图档' })
      .mockResolvedValueOnce(completed(true)).mockResolvedValue(completed(false))
    await resume(); expect(wrapper!.emitted('archived')).toBeUndefined()
    await vi.advanceTimersByTimeAsync(1800); await flushPromises()
    expect(wrapper!.emitted('archived')).toHaveLength(1)
    expect(document.body.textContent).toContain('图档已存档，预览正在后台生成')
    expect(footerButton('继续存档').disabled).toBe(false)
    expect(document.querySelector('.el-dialog__footer .pdm-primary-action')).toBeNull()
    await vi.advanceTimersByTimeAsync(1800); await flushPromises()
    expect(wrapper!.emitted('archived')).toHaveLength(2)
    expect(document.body.textContent).not.toContain('预览正在后台生成')
    await vi.advanceTimersByTimeAsync(10_000)
    expect(api.readBrowserCadTicket).toHaveBeenCalledTimes(3)
  })
  it('keeps native success when optional previews finish with warnings', async () => {
    vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout'] })
    api.readBrowserCadTicket.mockResolvedValueOnce(completed(true)).mockResolvedValue({ ...completed(false), warnings: ['PART.SLDPRT 预览生成失败，可稍后重试。'] })
    await resume(); await vi.advanceTimersByTimeAsync(1800); await flushPromises()
    expect(document.body.textContent).toContain('存档完成')
    expect(document.body.textContent).toContain('新增 1 个版本')
    expect(document.body.textContent).toContain('预览生成失败，可稍后重试')
    expect(document.querySelector('.browser-cad-error')).toBeNull()
    expect(footerButton('继续存档').disabled).toBe(false)
    expect(wrapper!.emitted('archived')).toHaveLength(2)
  })
  it('keeps polling after closing, and reopening reads the latest preview result', async () => {
    vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout'] })
    api.readBrowserCadTicket.mockResolvedValue(completed(true))
    await resume(); footerButton('后台继续').click(); await flushPromises()
    await vi.advanceTimersByTimeAsync(1800); await flushPromises()
    expect(api.readBrowserCadTicket).toHaveBeenCalledTimes(2)
    expect(wrapper!.emitted('archived')).toHaveLength(1)
    api.readBrowserCadTicket.mockResolvedValue(completed(false))
    await wrapper!.get('.browser-cad-entry').trigger('click'); await flushPromises()
    expect(api.readBrowserCadTicket).toHaveBeenCalledTimes(3)
    expect(wrapper!.emitted('archived')).toHaveLength(2)
    expect(footerButton('关闭')).toBeDefined()
  })
  it('resumes preview polling from the durable ticket after a page remount', async () => {
    vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout'] })
    api.readBrowserCadTicket.mockResolvedValue(completed(true))
    await resume(); wrapper!.unmount(); wrapper = undefined; document.body.innerHTML = ''
    await open(); await wrapper!.get('.browser-cad-entry').trigger('click'); await flushPromises()
    expect(api.readBrowserCadTicket).toHaveBeenLastCalledWith('job', 'token')
    expect(document.body.textContent).toContain('预览正在后台生成')
    expect(wrapper!.emitted('archived')).toHaveLength(1)
    api.readBrowserCadTicket.mockResolvedValue(completed(false))
    await vi.advanceTimersByTimeAsync(1800); await flushPromises()
    expect(wrapper!.emitted('archived')).toHaveLength(2)
    expect(api.readBrowserCadTicket).toHaveBeenCalledTimes(3)
  })
  it('deduplicates native and preview completion events across repeated status reads', async () => {
    vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout'] })
    api.readBrowserCadTicket.mockResolvedValue(completed(true))
    await resume(); await vi.advanceTimersByTimeAsync(5400); await flushPromises()
    expect(api.readBrowserCadTicket).toHaveBeenCalledTimes(4)
    expect(wrapper!.emitted('archived')).toHaveLength(1)
    api.readBrowserCadTicket.mockResolvedValue(completed(false))
    await vi.advanceTimersByTimeAsync(1800); await flushPromises()
    await wrapper!.get('.browser-cad-entry').trigger('click'); await flushPromises()
    await wrapper!.get('.browser-cad-entry').trigger('click'); await flushPromises()
    expect(wrapper!.emitted('archived')).toHaveLength(2)
  })
  it('does not restore a previous task when an in-flight preview read finishes after continue archiving', async () => {
    vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout'] })
    const oldRead = deferred<BrowserCadTicket>()
    api.readBrowserCadTicket.mockResolvedValueOnce(completed(true)).mockReturnValueOnce(oldRead.promise)
    await resume(); await vi.advanceTimersByTimeAsync(1800)
    footerButton('继续存档').click(); await flushPromises()
    api.stageBrowserCadArchive.mockResolvedValue({ ...completed(), id: 'new-job', state: 'Ready', stage: '新文件已接收', files: [{ relativePath: 'NEW.SLDPRT', length: 20 }] })
    const input = document.querySelector<HTMLInputElement>('input[aria-label="选择存档文件"]')!
    Object.defineProperty(input, 'files', { value: [new File(['new'], 'NEW.SLDPRT')] })
    input.dispatchEvent(new Event('change', { bubbles: true })); await flushPromises()
    oldRead.resolve(completed(false)); await flushPromises()
    expect(document.querySelector('.browser-cad-status')!.textContent).toContain('新文件已接收')
    expect(document.querySelector<HTMLSelectElement>('[aria-label="存档根图档"]')!.value).toBe('NEW.SLDPRT')
    expect(wrapper!.emitted('archived')).toHaveLength(1)
    expect(sessionStorage.getItem('uplm-cad-archive:project')).not.toBe('job')
    await vi.advanceTimersByTimeAsync(10_000)
    expect(api.readBrowserCadTicket).toHaveBeenCalledTimes(2)
  })
  it.each([{ token: 'another-token' }, { projectId: 'another-project' }])('ignores an old preview response after its context changes: %o', async changed => {
    vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout'] })
    const oldRead = deferred<BrowserCadTicket>()
    api.readBrowserCadTicket.mockResolvedValueOnce(completed(true)).mockReturnValueOnce(oldRead.promise)
    await resume(); await vi.advanceTimersByTimeAsync(1800)
    await wrapper!.setProps(changed)
    oldRead.resolve(completed(false)); await flushPromises()
    expect(document.querySelector('.browser-cad-status')).toBeNull()
    expect(wrapper!.emitted('archived')).toHaveLength(1)
    await vi.advanceTimersByTimeAsync(10_000)
    expect(api.readBrowserCadTicket).toHaveBeenCalledTimes(2)
  })
  it('does not continue polling legacy or standard structure results without a preview flag', async () => {
    vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout'] })
    const result = completed(); delete result.previewsPending
    api.readBrowserCadTicket.mockResolvedValue(result)
    sessionStorage.setItem('uplm-cad-archive:standard', 'job')
    wrapper = mount(BrowserCadArchiveButton, { attachTo: document.body, props: { token: 'token' }, global: { plugins: [ElementPlus] } })
    await flushPromises(); await wrapper.get('.browser-cad-entry').trigger('click'); await flushPromises()
    await vi.advanceTimersByTimeAsync(10_000)
    expect(wrapper!.emitted('archived')).toHaveLength(1)
    expect(api.readBrowserCadTicket).toHaveBeenCalledTimes(1)
    expect(document.body.textContent).not.toContain('预览正在后台生成')
    expect(footerButton('继续存档').disabled).toBe(false)
    expect(footerButton('重试预览')).toBeUndefined()
  })
  it('retries only previews, prevents duplicate requests and refreshes when the retry completes', async () => {
    vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout'] })
    const retry = deferred<BrowserCadTicket>()
    api.readBrowserCadTicket.mockResolvedValue({ ...completed(false), previewRetryable: true, warnings: ['部分预览生成失败。'] })
    api.retryBrowserCadPreviews.mockReturnValue(retry.promise)
    await resume()
    const button = footerButton('重试预览'); button.click(); button.click(); await flushPromises()
    expect(api.retryBrowserCadPreviews).toHaveBeenCalledExactlyOnceWith('job', 'token')
    expect(button.disabled).toBe(true)
    expect(document.body.textContent).toContain('存档成功')
    expect(footerButton('继续存档').disabled).toBe(false)
    api.readBrowserCadTicket.mockResolvedValue(completed(true))
    retry.resolve({ ...completed(true), previewRetryable: false }); await flushPromises()
    expect(document.body.textContent).toContain('预览正在后台生成')
    expect(footerButton('重试预览')).toBeUndefined()
    expect(wrapper!.emitted('archived')).toHaveLength(1)
    api.readBrowserCadTicket.mockResolvedValue(completed(false))
    await vi.advanceTimersByTimeAsync(1800); await flushPromises()
    expect(wrapper!.emitted('archived')).toHaveLength(2)
    expect(api.stageBrowserCadArchive).not.toHaveBeenCalled()
    expect(api.startBrowserCadArchive).not.toHaveBeenCalled()
  })
  it.each([
    ['当前账号没有项目存档权限。', '当前账号没有项目存档权限。'],
    ['Failed to fetch', '无法连接服务器，请检查网络后重试。'],
  ])('keeps native success and reports a Chinese retry error: %s', async (message, displayed) => {
    api.readBrowserCadTicket.mockResolvedValue({ ...completed(false), previewRetryable: true })
    api.retryBrowserCadPreviews.mockRejectedValue(new Error(message))
    await resume(); footerButton('重试预览').click(); await flushPromises()
    expect(document.querySelector('.browser-cad-error')!.textContent).toBe(displayed)
    expect(document.body.textContent).toContain('存档成功')
    expect(footerButton('重试预览').disabled).toBe(false)
    expect(footerButton('继续存档').disabled).toBe(false)
    expect(wrapper!.emitted('archived')).toHaveLength(1)
    expect(api.stageBrowserCadArchive).not.toHaveBeenCalled()
    expect(api.startBrowserCadArchive).not.toHaveBeenCalled()
  })
  it.each(['reset', 'token', 'project'])('ignores an old retry response after %s changes the context', async action => {
    vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout'] })
    const retry = deferred<BrowserCadTicket>()
    api.readBrowserCadTicket.mockResolvedValue({ ...completed(false), previewRetryable: true })
    api.retryBrowserCadPreviews.mockReturnValue(retry.promise)
    await resume(); footerButton('重试预览').click(); await flushPromises()
    if (action === 'reset') { footerButton('继续存档').click(); await flushPromises() }
    else await wrapper!.setProps(action === 'token' ? { token: 'new-token' } : { projectId: 'new-project' })
    retry.resolve(completed(true)); await flushPromises()
    expect(document.querySelector('.browser-cad-status')).toBeNull()
    expect(document.querySelector('.browser-cad-error')).toBeNull()
    expect(wrapper!.emitted('archived')).toHaveLength(1)
    await vi.advanceTimersByTimeAsync(10_000)
    expect(api.readBrowserCadTicket).toHaveBeenCalledTimes(1)
    expect(api.stageBrowserCadArchive).not.toHaveBeenCalled()
    expect(api.startBrowserCadArchive).not.toHaveBeenCalled()
  })
})
