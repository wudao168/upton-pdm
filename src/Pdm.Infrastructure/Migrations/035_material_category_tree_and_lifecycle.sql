CREATE TABLE material_category (
    category_code VARCHAR(20) NOT NULL PRIMARY KEY,
    category_name VARCHAR(120) NOT NULL,
    parent_code VARCHAR(20) NULL,
    u9_category_id VARCHAR(160) NULL,
    pdm_kind VARCHAR(30) NULL,
    default_supply_mode VARCHAR(30) NOT NULL DEFAULT 'Purchase',
    allow_create TINYINT(1) NOT NULL DEFAULT 0,
    is_visible TINYINT(1) NOT NULL DEFAULT 1,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    number_prefix VARCHAR(40) NOT NULL,
    sequence_length TINYINT UNSIGNED NOT NULL DEFAULT 7,
    counter_scope VARCHAR(40) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    updated_by VARCHAR(100) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    row_version BIGINT NOT NULL DEFAULT 1,
    UNIQUE KEY ux_material_category_u9_id (u9_category_id),
    KEY ix_material_category_parent (parent_code,sort_order,category_code),
    KEY ix_material_category_create (allow_create,is_visible,is_active),
    CONSTRAINT fk_material_category_parent FOREIGN KEY (parent_code) REFERENCES material_category(category_code),
    CONSTRAINT ck_material_category_sequence_length CHECK (sequence_length BETWEEN 1 AND 9)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

