ALTER TABLE material_master
    ADD COLUMN category_code VARCHAR(20) NULL AFTER material_kind,
    ADD COLUMN is_archived TINYINT(1) NOT NULL DEFAULT 0 AFTER sync_status,
    ADD COLUMN archived_by VARCHAR(100) NULL AFTER is_archived,
    ADD COLUMN archived_at DATETIME(6) NULL AFTER archived_by,
    ADD KEY ix_material_master_search (category_code,is_archived,material_code,name),
    ADD CONSTRAINT fk_material_master_category FOREIGN KEY (category_code) REFERENCES material_category(category_code);

UPDATE material_master
SET category_code=COALESCE(u9_category_code,
    CASE material_kind WHEN 'Electrical' THEN '0101' WHEN 'Standard' THEN '0102' WHEN 'NonStandard' THEN '0204' END)
WHERE category_code IS NULL;

